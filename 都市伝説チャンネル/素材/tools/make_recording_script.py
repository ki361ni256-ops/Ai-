PAT = re.compile("|".join(sorted(map(re.escape, RUBY), key=len, reverse=True)))

def ruby(text):
    seen, out, i = set(), [], 0
    for m in PAT.finditer(text):
        w = m.group(0)
        out.append(text[i:m.end()])
        if w not in seen and not text[m.end():].startswith("（"):
            out.append(f"（{RUBY[w]}）"); seen.add(w)
        i = m.end()
    out.append(text[i:])
    return "".join(out)

def main(ep, name):
    ep = pathlib.Path(ep)
    L = script_lines(ep / "03_台本_長尺.md"); S = script_lines(ep / "03_台本_ショート.md")
    out = [f"# 収録台本：{name}\n\n## 録り方\n- 番号の順に、上から読む。**番号と番号のあいだは1〜2秒あける**。番号は読まない\n"
           "- 言い間違えたら、2秒以上あけて**その番号の頭から**読み直す\n- （ ）の中はふりがな。読まない\n- 長尺とショートは別々のファイルで録る\n"
           "- スマホはタオルの上に置き、エアコン・換気扇を止めると雑音が減ります\n\n---\n\n# 長尺\n"]
    for i, (t, x, new) in enumerate(L):
        if new and i: out.append("\n---\n")
        out.append(f"\n**{i + 1:03d}**　{ruby(x)}\n")
    out.append(f"\n（長尺：全{len(L)}行）\n\n---\n\n# ショート\n")
    for i, (t, x, new) in enumerate(S):
        out.append(f"\n**{i + 1:03d}**　{ruby(x)}\n")
    out.append(f"\n（ショート：全{len(S)}行）\n")
    dst = pathlib.Path(__file__).resolve().parents[2] / "収録台本" / f"{name}.md"
    dst.write_text("".join(out)); print(dst, len(L), len(S))

